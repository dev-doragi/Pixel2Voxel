"""Reproducible bundle: modular source, single runtime script (no host require resolution)."""
from pathlib import Path
import zipfile, sys
root=Path(__file__).resolve().parents[1];src=root/'extensions/pixel2voxel'
out=Path(sys.argv[1]) if len(sys.argv)>1 else root/'Pixel2Voxel-0.1.0.aseprite-extension'
modules=['core/volume','core/generate','render/raster','host/images','ui/workspace']
parts=['-- Generated from modular sources; do not edit this file directly.\nlocal factories, loaded = {}, {}\nlocal function require(name)\n  if loaded[name] then return loaded[name] end\n  local factory=assert(factories[name], "Missing module: "..name)\n  local value=factory(); loaded[name]=value; return value\nend\n']
for name in modules:
    parts.append('factories[%r] = function()\n%s\nend\n' %(name.replace('/','.'),(src/(name+'.lua')).read_text(encoding='utf-8')))
parts.append((src/'main.lua').read_text(encoding='utf-8'));bundle=''.join(parts).encode()
with zipfile.ZipFile(out,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
    for name,data in sorted({'main.lua':bundle,**{x:(src/x).read_bytes() for x in ['package.json','LICENSE','README.md']}}.items()):
        info=zipfile.ZipInfo(name,(2026,1,1,0,0,0));info.compress_type=zipfile.ZIP_DEFLATED;info.external_attr=0o644<<16;z.writestr(info,data,compresslevel=9)
print(out,out.stat().st_size,'bytes')
