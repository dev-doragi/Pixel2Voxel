namespace PixelVoxel.Core;

/// <summary>
/// Identifies one of the six named orthographic faces of a voxel model.
/// </summary>
public enum VoxelFace
{
    /// <summary>The front face.</summary>
    Front,

    /// <summary>The back face.</summary>
    Back,

    /// <summary>The left face.</summary>
    Left,

    /// <summary>The right face.</summary>
    Right,

    /// <summary>The top face.</summary>
    Top,

    /// <summary>The bottom face.</summary>
    Bottom,
}

